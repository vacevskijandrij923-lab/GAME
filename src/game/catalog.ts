function generateFleetCars(): CarSpec[] {
  const generated: CarSpec[] = [];
  const totalNeeded = 1000 - SIGNATURE_CARS.length; // 976 cars
  const usedNames = new Set(SIGNATURE_CARS.map((c) => c.name));

  for (let i = 0; i < totalNeeded; i++) {
    const t = i / (totalNeeded - 1); // 0..1 progression
    const tier: CarSpec['tier'] =
      t < 0.18
        ? 'Starter'
        : t < 0.42
        ? 'Street'
        : t < 0.66
        ? 'Heavy'
        : t < 0.86
        ? 'Apex'
        : 'Titan';

    const shapes = TIER_SHAPES[tier];
    const bodyShape = shapes[(i * 3 + Math.floor(i / 7)) % shapes.length];
    const brand = BRAND_PREFIXES[(i * 5 + 3) % BRAND_PREFIXES.length];
    const models = SHAPE_MODELS[bodyShape];
    const model = models[(i * 7 + 1) % models.length];
    const edition = EDITIONS[(i * 11 + 2) % EDITIONS.length];
    const paint = PAINT_FINISHES[(i * 13 + 5) % PAINT_FINISHES.length];

    const seriesNum = 100 + ((i * 17) % 899);
    let name = `${brand} ${model} ${edition}`;
    if (usedNames.has(name)) {
      name = `${brand} ${paint.name} ${model} ${seriesNum}`;
    }
    if (usedNames.has(name)) {
      name = `${brand} ${model} #${i + 25}`;
    }
    usedNames.add(name);

    // Smooth price curve from $150 up to $500,000
    const curved = Math.pow(t, 2.35);
    const rawPrice = 150 + curved * 499850;
    const price =
      rawPrice < 1000
        ? Math.round(rawPrice / 25) * 25
        : rawPrice < 10000
        ? Math.round(rawPrice / 100) * 100
        : Math.round(rawPrice / 500) * 500;

    const isBig =
      bodyShape === 'bus' || bodyShape === 'bulldozer' || bodyShape === 'monster';
    const isFast = bodyShape === 'supercar' || bodyShape === 'coupe' || bodyShape === 'muscle';

    const baseWidth =
      bodyShape === 'monster'
        ? 38
        : bodyShape === 'bulldozer'
        ? 36
        : bodyShape === 'bus'
        ? 32
        : bodyShape === 'van' || bodyShape === 'truck'
        ? 30
        : bodyShape === 'supercar'
        ? 29
        : 25;
    const baseLength =
      bodyShape === 'bus'
        ? 76
        : bodyShape === 'monster'
        ? 68
        : bodyShape === 'bulldozer'
        ? 64
        : bodyShape === 'van'
        ? 60
        : bodyShape === 'truck'
        ? 56
        : bodyShape === 'supercar'
        ? 55
        : 46;

    const speedBonus = isFast ? 115 : isBig ? -25 : 30;
    const maxSpeed = Math.round(425 + t * 335 + speedBonus + ((i % 7) - 3) * 6);
    const accel = Math.round(maxSpeed * (isFast ? 1.38 : 1.18));
    const handling = Number(
      (isBig ? 2.75 + t * 0.95 : 3.45 + t * 1.3 + (i % 5) * 0.05).toFixed(2)
    );
    const mass = Number((1.05 + t * 5.2 + (isBig ? 0.8 : 0)).toFixed(2));
    const smashPower = Number((1.05 + t * 5.5 + (isBig ? 0.9 : 0)).toFixed(2));
    const maxHp = Math.round(115 + t * 620 + (isBig ? 90 : 0));
    const cashMultiplier = Number((1.05 + t * 3.8).toFixed(2));

    generated.push({
      id: `fleet-${String(i + 25).padStart(4, '0')}`,
      name,
      tagline: `${paint.name} finish. ${TAGLINE_VERBS[i % TAGLINE_VERBS.length]}`,
      tier,
      price,
      maxSpeed,
      accel,
      handling,
      mass,
      smashPower,
      maxHp,
      cashMultiplier,
      width: baseWidth,
      length: baseLength,
      bodyShape,
      primaryColor: paint.primary,
      secondaryColor: paint.secondary,
      accentColor: paint.accent,
    });
  }

  return generated;
}

